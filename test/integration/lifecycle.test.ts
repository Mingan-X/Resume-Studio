await test('S3.2 durable deletion resumes exact stores, fences new work, retains account and refuses uncertain workers',{timeout:180000},async t=>{
 await ownedPostgres();await ownedQdrant();const config=loadInfrastructureConfig(process.env),database=new DatabaseService(config),db=database.client;
 const root=await mkdtemp(join(tmpdir(),'resume-lifecycle-')),files=await LocalStorage.create(root),owners:string[]=[],threads=new Set<string>();
 const checkpoint=loadCheckpointConfig(process.env),session=createCheckpointStore(checkpoint),vector=new JobIndexVector({url:config.qdrantUrl,apiKey:config.qdrantApiKey},ownedQdrant);
 const repo=new LifecycleRepository(database),traces={baseUrl:'http://127.0.0.1:53000',publicKey:'unused',secretKey:'unused'};
 const stores=new LifecycleStorage(files,vector,checkpoint,traces);
 t.after(async()=>{try{await ownedPostgres();for(const thread of threads)await session.saver.deleteThread(thread);
  for(const owner of owners){await db.deletionRequest.deleteMany({where:{ownerId:owner}});await vector.eraseOwner(owner,{signal:AbortSignal.timeout(30000),deadline:Date.now()+30000});
   await db.account.deleteMany({where:{ownerId:owner}});await cleanRealAnalysis(database,owner);}
 }finally{await session.close();await database.onModuleDestroy();assert.ok(!relative(resolve(tmpdir()),resolve(root)).startsWith('..'));await rm(root,{recursive:true});}});
 const seed=async(age:number)=>{
  const owner=randomUUID();owners.push(owner);const file=await files.stage(Readable.from(Buffer.from('Synthetic lifecycle file')));await files.commit(file);
  const fixture=await seedRealAnalysis(database,owner,{file,uploadedAt:new Date(Date.now()-age*86400000)});threads.add(fixture.taskId);
  const account=await db.account.create({data:{id:randomUUID(),ownerId:owner,username:`life-${randomUUID()}`,passwordHash:await hashPassword('synthetic-lifecycle-password')}});
  return {owner,file,fixture,account};
 };
 const active=await seed(31),other=await seed(1);
 const store=new TaskExecutionStore(database,consumerConfigSchema.parse({}));
 const claimed=await store.claim(active.owner,active.fixture.message,'analysis',active.fixture.snapshot.embeddingVersion,active.fixture.snapshot.modelConfigVersion);
 if(claimed.kind!=='acquired')assert.fail();
 const olderThread=randomUUID();threads.add(olderThread);await db.taskCheckpointThread.create({data:{ownerId:active.owner,taskId:active.fixture.taskId,threadId:olderThread}});
 for(const thread of [active.fixture.taskId,olderThread])await session.saver.put({configurable:{thread_id:thread,checkpoint_ns:''}},emptyCheckpoint(),{source:'input',step:-1,parents:{}},{});
 const spec=indexCollectionSchema.parse({...active.fixture.settings.indexTarget,ownerId:active.owner,dimensions:4,provenance:'synthetic'});
 await vector.ensure(spec,{signal:AbortSignal.timeout(30000),deadline:Date.now()+30000});await vector.switchAlias(spec,{signal:AbortSignal.timeout(15000),deadline:Date.now()+15000});
 const operation=await repo.begin(active.owner,'UPLOAD'),request=await repo.request(active.owner,randomUUID());
 assert.equal(await repo.request(active.owner,randomUUID()),request);
 await assert.rejects(repo.get(other.owner,request),/Not Found/);
 await assert.rejects(new TaskRepository(database).createAnalysis(randomUUID(),{...analysisInput(),ownerId:active.owner}));
 await assert.rejects(repo.begin(active.owner,'UPLOAD'));
 const executor=new LifecycleExecutor(database,stores);
 assert.equal(await executor.run(request),'waiting');assert.equal((await repo.get(active.owner,request)).reason,'ACTIVE_EXECUTION');
 await repo.stopped(operation.id);assert.equal(await executor.run(request),'waiting','terminal cancelled task without stopped evidence must wait');
 assert.equal((await db.analysisTask.findUniqueOrThrow({where:{id:active.fixture.taskId}})).status,'CANCELLED');
 assert.equal((await files.read(active.file.storageKey)).length,active.file.size);
 await store.markExecutionStopped(claimed.claim);
 await db.analysisTask.update({where:{id:active.fixture.taskId},data:{lifecycleHistoryComplete:false}});
 assert.equal(await executor.run(request),'waiting');assert.equal((await repo.get(active.owner,request)).reason,'INCOMPLETE_HISTORY');
 // This synthetic fixture has an explicit complete thread list; no production inference.
 await db.analysisTask.update({where:{id:active.fixture.taskId},data:{lifecycleHistoryComplete:true}});
 await db.account.update({where:{id:active.account.id},data:{lifecycleHistoryComplete:false}});
 assert.equal(await executor.run(request),'waiting');assert.equal((await repo.get(active.owner,request)).reason,'INCOMPLETE_HISTORY');
 await db.account.update({where:{id:active.account.id},data:{lifecycleHistoryComplete:true}});
 let fail=true;
 const interrupted=new LifecycleExecutor(database,{erase:async(resource,signal,deadline)=>{await stores.erase(resource,signal,deadline);if(fail&&resource.kind==='FILE'){fail=false;throw new Error('lost completion reply');}}});
 assert.equal(await interrupted.run(request),'waiting');assert.equal((await repo.get(active.owner,request)).status,'RUNNING');
 assert.equal(await db.resumeVersion.count({where:{ownerId:active.owner}}),1,'DB references survive external-step failure');
 await db.deletionStep.updateMany({where:{requestId:request},data:{retryAt:new Date(0)}});
 assert.equal(await new LifecycleExecutor(database,stores).run(request),'done');assert.equal(await executor.run(request),'done');
 assert.equal(await db.account.count({where:{id:active.account.id}}),1);assert.equal(await db.job.count({where:{ownerId:active.owner}}),0);
 assert.equal(await db.rubricVersion.count({where:{ownerId:active.owner}}),0);assert.equal(await db.scoringPolicy.count({where:{ownerId:active.owner}}),0);
 assert.equal(await vector.exists(spec,{signal:AbortSignal.timeout(15000),deadline:Date.now()+15000}),false);
 for(const thread of [active.fixture.taskId,olderThread])assert.equal(await session.saver.getTuple({configurable:{thread_id:thread}}),undefined);
 await assert.rejects(files.read(active.file.storageKey));assert.equal((await files.read(other.file.storageKey)).length,other.file.size);
 assert.equal(await db.deletionStep.count({where:{requestId:request}}),0);assert.equal(await db.owner.count({where:{id:active.owner}}),1);
 const expired=await seed(31),recent=await seed(29);
 const due=await repo.due(100);assert.ok(due.length);const retention=await db.deletionRequest.findFirstOrThrow({where:{ownerId:expired.owner,scope:'RESUME'}});
 assert.equal(await db.deletionRequest.count({where:{ownerId:recent.owner}}),0);
 assert.equal(await executor.run(retention.id),'waiting','expiry never cancels an active task');assert.equal((await db.analysisTask.findUniqueOrThrow({where:{id:expired.fixture.taskId}})).cancelRequested,false);
 await db.analysisTask.update({where:{id:expired.fixture.taskId},data:{status:'FAILED'}});
 assert.equal(await executor.run(retention.id),'done');assert.equal(await db.resume.count({where:{ownerId:expired.owner}}),0);
 assert.equal(await db.job.count({where:{ownerId:expired.owner}}),1);assert.equal(await db.jobCorpusVersion.count({where:{ownerId:expired.owner}}),1);
 assert.equal((await readdir(join(root,'files'))).includes(other.file.storageKey),true);
});
